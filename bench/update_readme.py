#!/usr/bin/env python3
"""
Splice bench/table.py's output into the README between the BENCH markers.

The numbers in a README about not trusting unverified claims should not be
retyped by hand. Run this after adding a model; it rewrites only what is
between the markers.
"""
import io
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
README = os.path.join(HERE, os.pardir, "README.md")
START = "<!-- BENCH:START - generated by bench/table.py, do not edit by hand -->"
END = "<!-- BENCH:END -->"


def main():
    table = subprocess.run([sys.executable, os.path.join(HERE, "table.py")],
                           capture_output=True, text=True, check=True).stdout.strip()
    s = io.open(README, encoding="utf-8").read()
    if START not in s or END not in s:
        print("markers missing from README")
        return 1
    new = START + "\n" + table + "\n" + END
    s = re.sub(re.escape(START) + r".*?" + re.escape(END), new, s, flags=re.S)
    io.open(README, "w", encoding="utf-8", newline="\n").write(s)
    print("README table updated from %d result file(s)"
          % len([f for f in os.listdir(HERE) if f.startswith("results-")]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
